"""Translate the supported flat raster record without altering its BMP image.

Native EMX 3.7 stores the BMP and raster settings; LenMark rebuilds its scan
cache on load. Legacy 3.0 embeds float32 XYZ/gray cache rows. We validate
that those rows form the expected flat DPI grid before allowing regeneration.
Attached, warped, rotated, or nonuniform raster caches are rejected.
"""
from __future__ import annotations

import hashlib
import math
import struct


_MAX_RASTER_PIXELS = 16_000_000
_MAX_BMP_BYTES = 256 * 1024 * 1024
_CACHE_POINT = struct.Struct("<3fB")
_NOTE = ("Bitmap scan cache will be regenerated by LenMark from the preserved "
         "BMP and processing settings; the legacy flat raster cache was validated.")


def _read_exact(cursor, count: int) -> bytes:
    # Binary reads are only made immediately after consuming a text marker.
    if getattr(cursor, "_peek", None) is not None:
        cursor.fail("Internal bitmap parser error: pending text before binary data")
    data = cursor.stream.read(count)
    if len(data) != count:
        cursor.fail(f"Truncated bitmap binary payload: expected {count} bytes")
    return data


def _close(actual: float, expected: float) -> bool:
    # Cached positions are float32; source text points have six decimals.
    tolerance = max(0.000006, abs(expected) * 0.0000002)
    return abs(actual - expected) <= tolerance


def _raster(cursor, rows: int, columns: int, dpi: int, origin: tuple[float, ...]):
    """Validate and consume old cache rows, returning their actual XYZ bounds."""
    if rows <= 0 or columns <= 0 or rows * columns > _MAX_RASTER_PIXELS:
        cursor.fail("Invalid or excessive bitmap raster dimensions")
    if not 0 < dpi <= 1_000_000:
        cursor.fail("Unsupported bitmap DPI")
    spacing = 25.4 / dpi
    first_x = first_y = first_z = None
    low = [math.inf, math.inf, math.inf]
    high = [-math.inf, -math.inf, -math.inf]
    for row in range(rows):
        marker = cursor.field(216)
        try:
            row_index, count = (int(x) for x in marker.split(b":"))
        except ValueError:
            cursor.fail("Malformed bitmap raster row")
        if row_index != row or count != columns:
            cursor.fail("Bitmap raster row indices or pixel counts are inconsistent")
        data = _read_exact(cursor, columns * _CACHE_POINT.size)
        for column, (x, y, z, _gray) in enumerate(_CACHE_POINT.iter_unpack(data)):
            if not all(math.isfinite(v) for v in (x, y, z)):
                cursor.fail("Non-finite bitmap raster coordinate")
            if first_x is None:
                first_x, first_y, first_z = x, y, z
            if not (_close(x, first_x + column * spacing)
                    and _close(y, first_y + row * spacing)
                    and _close(z, first_z)):
                cursor.fail("Unsupported warped, rotated, or nonuniform bitmap raster cache")
            for axis, value in enumerate((x, y, z)):
                low[axis] = min(low[axis], value)
                high[axis] = max(high[axis], value)
    if not (_close(origin[0], first_x)
            and _close(origin[1], first_y + (rows - 1) * spacing)
            and _close(origin[2], first_z)):
        cursor.fail("Bitmap control point does not match the legacy raster grid")
    return (low[0], high[0], low[1], high[1], low[2], high[2])


def _copy_bmp(c, original_width: int, original_height: int) -> tuple[int, str]:
    header = _read_exact(c.cursor, 54)
    if header[:2] != b"BM":
        c.cursor.fail("Missing embedded BMP signature")
    size, reserved1, reserved2, bits_offset = struct.unpack_from("<IHHI", header, 2)
    (dib_size, width, height, planes, bits, compression, image_size,
     _x_dpi, _y_dpi, used_colors, _important) = struct.unpack_from("<IiiHHIIiiII", header, 14)
    if dib_size != 40 or planes != 1 or compression != 0 or bits not in (1, 4, 8, 16, 24, 32):
        c.cursor.fail("Unsupported embedded BMP layout (requires uncompressed BITMAPINFOHEADER)")
    if width <= 0 or height <= 0 or (width, height) != (original_width, original_height):
        c.cursor.fail("Embedded BMP dimensions disagree with the legacy bitmap settings")
    if reserved1 or reserved2:
        c.cursor.fail("Unsupported nonzero BMP reserved fields")
    stride = ((width * bits + 31) // 32) * 4
    pixel_bytes = stride * height
    palette_bytes = 0
    if bits <= 8:
        if used_colors > 1 << bits:
            c.cursor.fail("Invalid BMP palette size")
        palette_bytes = (used_colors or (1 << bits)) * 4
    if (size > _MAX_BMP_BYTES or size < 54 or bits_offset < 54 + palette_bytes
            or bits_offset + pixel_bytes != size or image_size not in (0, pixel_bytes)):
        c.cursor.fail("Invalid BMP size, palette, or pixel offset")
    digest = hashlib.sha256(header)
    c.writer.raw(header)
    remaining = size - len(header)
    while remaining:
        data = _read_exact(c.cursor, min(remaining, 1024 * 1024))
        digest.update(data)
        c.writer.raw(data)
        remaining -= len(data)
    return size, digest.hexdigest()


def write_bitmap(c) -> None:
    """Write a Bitmap body; caller consumed ``Bitmap``, consume ``BitmapEnd``."""
    kind = c.entity()
    if kind != 13:
        c.cursor.fail(f"Bitmap record has entity type {kind}, expected 13")
    if getattr(c, "last_entity_attached", None) != 0:
        c.cursor.fail("Attached bitmap archives require an unmapped external cache and are unsupported")
    c.cursor.expect(b"201")
    c.cursor.expect(b"CSPoint")
    origin = tuple(c.number(tag, "d") for tag in (201, 202, 203))
    c.cursor.expect(b"CSPointEnd")
    point_bytes = struct.pack("<3d", *origin)
    c.writer.raw(point_bytes)
    c.coordinate_hash.update(point_bytes)
    c.counts["points"] += 1
    bounds_position = c.writer.reserve(48)
    # All remaining scalar settings precede the BMP in the target archive.
    settings_position = c.writer.reserve(16 + 20 + 24 + 36 + 2 + 55 + 8)
    settings = {tag: c.number(tag, "i") for tag in range(202, 211)}
    settings[212] = c.number(212, "i")
    curve = []
    for index in range(11):
        value = c.cursor.field(213)
        try:
            curve_index, gray = (int(x) for x in value.split(b":"))
        except ValueError:
            c.cursor.fail("Malformed bitmap power/gray curve")
        if curve_index != index or not 0 <= gray <= 255:
            c.cursor.fail("Bitmap power/gray curve must contain entries 0 through 10")
        curve.append(gray)
    rows, columns = c.number(214, "i"), c.number(215, "i")
    if (settings[202], settings[203]) != (columns, rows):
        c.cursor.fail("Bitmap processing dimensions disagree with its raster cache")
    bounds = _raster(c.cursor, rows, columns, settings[210], origin)
    for tag in range(217, 229):
        settings[tag] = c.number(tag, "d" if tag in (224, 225, 228) else "i")
    for tag in (221, 222):
        if not 0 <= settings[tag] <= 255:
            c.cursor.fail("Bitmap grayscale limits must fit an unsigned byte")
    c.writer.patch(bounds_position, "6d", *bounds)
    end_position = c.writer.stream.tell()
    c.writer.stream.seek(settings_position)
    c.writer.pack("4i", *(settings[t] for t in (202, 203, 204, 205)))
    c.writer.pack("5i", settings[206], 0, settings[217], settings[218], settings[219])
    c.writer.pack("3d", settings[228], settings[224], settings[225])
    c.writer.pack("9i", *(settings[t] for t in (226, 227, 207, 208, 209, 210, 212, 223, 220)))
    c.writer.pack("2B", settings[221], settings[222])
    for index, gray in enumerate(curve):
        c.writer.pack("Bf", gray, index * 10.0)
    c.writer.pack("2i", rows, columns)
    if c.writer.stream.tell() != end_position:
        c.cursor.fail("Internal bitmap settings size mismatch")
    c.cursor.expect(b"211")
    size, digest = _copy_bmp(c, settings[204], settings[205])
    c.cursor.expect(b"BitmapEnd")
    c.counts["bitmap_images"] += 1
    c.counts["bitmap_bytes"] += size
    c.counts["bitmap_pixels"] += settings[204] * settings[205]
    c.counts["raster_pixels"] += rows * columns
    c.counts["bitmap_cached_pixels"] += rows * columns
    c.counts["bitmap_cache_regenerated"] += 1
    if not hasattr(c, "bitmap_bmp_sha256"):
        c.bitmap_bmp_sha256 = []
    c.bitmap_bmp_sha256.append(digest)
    if not hasattr(c, "conversion_notes"):
        c.conversion_notes = []
    if _NOTE not in c.conversion_notes:
        c.conversion_notes.append(_NOTE)
